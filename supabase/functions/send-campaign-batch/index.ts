// Campaign sends must always reach a terminal state.
// External provider failures are marked as failed immediately so the campaign can finish.
const RETRYABLE_ERRORS: Record<string, { maxRetries: number; delayHours: number[] }> = {};

// No Meta business error should bounce back to pending automatically.
// This was causing looping recipients and unstable counters.
const THROTTLE_ERRORS: string[] = [];

const PERMANENT_ERRORS = [
  '131026', '131042', '131021', '131047', '132001', '132000', '100', '135000',
];

function getFirstName(fullName: string | undefined): string {
  if (!fullName) return '';
  return fullName.split(' ')[0];
}

function isAutoGeneratedLeadName(name?: string | null): boolean {
  return !name || name.startsWith('LeadWhats-') || name.startsWith('WhatsApp ');
}

function getPhoneLookupKeys(phone: string): string[] {
  const digits = phone.replace(/\D/g, '');
  if (!digits) return [];

  const withoutCountryCode = digits.startsWith('55') ? digits.slice(2) : digits;

  return [...new Set([
    digits,
    withoutCountryCode,
    withoutCountryCode.slice(-9),
    withoutCountryCode.slice(-8),
  ].filter(Boolean))];
}

function setPreferredName(map: Map<string, string>, key: string, name?: string | null) {
  if (!key || !name) return;

  const current = map.get(key);
  if (!current || (isAutoGeneratedLeadName(current) && !isAutoGeneratedLeadName(name))) {
    map.set(key, name);
  }
}

